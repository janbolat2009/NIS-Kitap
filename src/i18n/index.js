import { ref, computed } from 'vue';

const LOCALE_KEY = 'nis_kitap_locale';

// Поддерживаемые языки: 'kz', 'ru', 'en'
const savedLocale = localStorage.getItem(LOCALE_KEY);
export const currentLocale = ref(savedLocale && ['kz', 'ru', 'en'].includes(savedLocale) ? savedLocale : 'ru');

export function setLocale(locale) {
  if (['kz', 'ru', 'en'].includes(locale)) {
    currentLocale.value = locale;
    localStorage.setItem(LOCALE_KEY, locale);
    document.documentElement.lang = locale === 'kz' ? 'kk' : locale;
  }
}

