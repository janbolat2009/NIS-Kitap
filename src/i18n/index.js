/**
 * Функция перевода t(key)
 * Например: t('nav.home') или t('catalog.foundCount')
 */
export function t(key, params = {}) {
  const loc = currentLocale.value || 'ru';
  const dict = translations[loc] || translations.ru;
  const fallbackDict = translations.ru;

  const getNested = (obj, path) => {
    return path.split('.').reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);
  };

  let val = getNested(dict, key);
  if (val === undefined) {
    val = getNested(fallbackDict, key);
  }

  if (typeof val === 'string') {
    Object.keys(params).forEach((paramKey) => {
      val = val.replace(new RegExp(`{${paramKey}}`, 'g'), params[paramKey]);
    });
    return val;
  }

  return val !== undefined ? val : key;
}

export function useI18n() {
  return {
    locale: currentLocale,
    setLocale,
    t,
  };
}
